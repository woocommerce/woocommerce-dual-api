<?php

declare(strict_types=1);

if ( PHP_VERSION_ID < 80100 ) {
	fwrite(
		STDERR,
		sprintf(
			"Error: PHP 8.1 or later is required. Current version: %s.\n",
			PHP_VERSION
		)
	);
	exit( 2 );
}

$options = getopt(
	'h',
	array(
		'help',
		'api-dir:',
		'autogen-dir:',
	)
);

$usage = <<<'TXT'
Usage: php check-api-staleness.php --api-dir=PATH --autogen-dir=PATH

Exits with status 1 when the generated code under --autogen-dir was not
produced from the current contents of --api-dir (the code-API sources), so
CI can enforce that both are committed together. Plugins using the
conventional layout pass their src/Api and src/Internal/Api/Autogenerated.

TXT;

if ( isset( $options['h'] ) || isset( $options['help'] ) ) {
	echo $usage;
	exit( 0 );
}

$api_dir     = $options['api-dir'] ?? null;
$autogen_dir = $options['autogen-dir'] ?? null;
if ( ! is_string( $api_dir ) || ! is_string( $autogen_dir ) ) {
	fwrite( STDERR, "Error: both --api-dir and --autogen-dir are required, each exactly once.\n\n" );
	fwrite( STDERR, $usage );
	exit( 2 );
}

require_once __DIR__ . '/../../vendor/autoload.php';

use Automattic\WooCommerce\Api\Infrastructure\DesignTime\StalenessChecker;

if ( StalenessChecker::is_stale( $api_dir, $autogen_dir ) ) {
	fwrite( STDERR, "ERROR: Generated GraphQL API code is out of date.\n" );
	fwrite( STDERR, "Run the API build script to regenerate it.\n" );
	exit( 1 );
}

echo "GraphQL API code is up to date.\n";
exit( 0 );
